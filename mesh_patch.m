function h = mesh_patch(ax, M, lighting, spec)
% MESH_PATCH  Render a combined mesh struct as a single optimized MATLAB patch.
    h = patch('Parent', ax, ...
        'Vertices',         M.V, ...
        'Faces',            M.F, ...
        'FaceVertexCData',  M.C, ...
        'FaceColor',        'interp', ...
        'EdgeColor',        'none', ...
        'FaceLighting',     lighting, ...
        'AmbientStrength',  0.40, ...
        'DiffuseStrength',  0.88, ...
        'SpecularStrength', spec, ...
        'SpecularExponent', 22, ...
        'BackFaceLighting', 'reverselit', ...
        'Clipping',         'off');
end